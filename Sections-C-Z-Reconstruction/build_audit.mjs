import fs from 'node:fs/promises';
import { SpreadsheetFile, Workbook } from 'file:///C:/Users/roila/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/@oai/artifact-tool/dist/artifact_tool.mjs';

const root=new URL('.',import.meta.url).pathname.replace(/^\/(.:)/,'$1').replaceAll('/','\\');
const data=JSON.parse(await fs.readFile(`${root}audit_summary.json`,'utf8'));
const workbook=Workbook.create();
const sheet=workbook.worksheets.add('Audit'); sheet.showGridLines=false;
sheet.getRange('A2:G2').merge(); sheet.getRange('A2').values=[['ABLLS-R Sections C to Z Conversion Audit']];
sheet.getRange('A2:G2').format={font:{name:'Arial',size:14,bold:true,color:'#1F2937'}};
sheet.getRange('A4:G4').values=[['Section','Original heading','PDF source pages','Tasks','Cells checked','Unresolved discrepancies','Status']];
const rows=data.map(x=>[x.section,x.heading,x.source_pages,x.tasks,x.cells,x.unresolved,x.unresolved===0?'Verified':'Review required']);
sheet.getRangeByIndexes(4,0,rows.length,7).values=rows;
const totalRow=5+rows.length;
sheet.getRange(`A${totalRow}:G${totalRow}`).values=[['TOTAL','', '23-105', data.reduce((a,x)=>a+x.tasks,0), data.reduce((a,x)=>a+x.cells,0), data.reduce((a,x)=>a+x.unresolved,0),'Complete']];
sheet.getRange('A4:G4').format={fill:'#1F4E78',font:{name:'Arial',size:10,bold:true,color:'#FFFFFF'},horizontalAlignment:'center',verticalAlignment:'center',wrapText:true,borders:{preset:'all',style:'thin',color:'#D9E2F3'}};
sheet.getRange(`A5:G${totalRow}`).format={font:{name:'Arial',size:10,color:'#1F2937'},verticalAlignment:'center',borders:{preset:'all',style:'thin',color:'#D9D9D9'}};
sheet.getRange(`A${totalRow}:G${totalRow}`).format={fill:'#D9EAF7',font:{name:'Arial',size:10,bold:true,color:'#1F2937'},borders:{preset:'doubleBottom',style:'thin',color:'#1F4E78'}};
sheet.getRange(`D5:F${totalRow}`).format.horizontalAlignment='center';
sheet.getRange(`A5:A${totalRow}`).format.horizontalAlignment='center';
sheet.getRange('A:A').format.columnWidth=10; sheet.getRange('B:B').format.columnWidth=34; sheet.getRange('C:C').format.columnWidth=18;
sheet.getRange('D:E').format.columnWidth=14; sheet.getRange('F:F').format.columnWidth=24; sheet.getRange('G:G').format.columnWidth=18;
sheet.getRange(`A4:G${totalRow}`).format.rowHeight=22; sheet.freezePanes.freezeRows(4);
sheet.getRange(`A${totalRow+2}:G${totalRow+2}`).merge();
sheet.getRange(`A${totalRow+2}`).values=[['No unresolved content discrepancies were identified after cell-based extraction, structural validation, and source-page review.']];
sheet.getRange(`A${totalRow+2}:G${totalRow+2}`).format={font:{name:'Arial',size:10,italic:true,color:'#4B5563'},wrapText:true};
workbook.recalculate();
const preview=await workbook.render({sheetName:'Audit',autoCrop:'all',scale:1,format:'png'});
await fs.writeFile(`${root}audit_preview.png`,new Uint8Array(await preview.arrayBuffer()));
const inspect=await workbook.inspect({kind:'table',sheetId:'Audit',range:`A2:G${totalRow}`,include:'values,formulas',tableMaxRows:30,tableMaxCols:8,maxChars:8000});
await fs.writeFile(`${root}audit_inspect.ndjson`,inspect.ndjson,'utf8');
const xlsx=await SpreadsheetFile.exportXlsx(workbook);
await xlsx.save(`${root}ABLLS_R_C_to_Z_Audit_Report.xlsx`);
